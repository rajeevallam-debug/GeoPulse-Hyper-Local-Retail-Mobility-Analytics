CREATE TABLE IF NOT EXISTS dq_summary (
    dataset TEXT,
    original_rows BIGINT,
    cleaned_rows BIGINT,
    rows_removed BIGINT,
    original_columns INTEGER,
    missing_cells_before BIGINT,
    missing_cells_after BIGINT,
    duplicate_rows_before BIGINT,
    duplicate_rows_after BIGINT
);

CREATE TABLE IF NOT EXISTS field_quality (
    dataset TEXT,
    column_name TEXT,
    missing_values BIGINT,
    missing_pct NUMERIC(8, 4),
    data_type TEXT,
    unique_values BIGINT
);

CREATE TABLE IF NOT EXISTS dq_findings (
    dataset TEXT,
    issue TEXT,
    column_name TEXT,
    issue_count BIGINT,
    action_recommendation TEXT
);
