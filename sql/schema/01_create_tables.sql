CREATE TABLE IF NOT EXISTS businesses (
    business_name TEXT,
    city TEXT,
    zip_code TEXT,
    borough TEXT,
    community_board INTEGER,
    council_district INTEGER,
    bin BIGINT,
    bbl NUMERIC(20, 0),
    census_tract_2010 BIGINT,
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7)
);

CREATE TABLE IF NOT EXISTS smart_mobility (
    recorded_at TIMESTAMP,
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    vehicle_count INTEGER,
    traffic_speed_kmh NUMERIC(12, 4),
    road_occupancy_pct NUMERIC(8, 4),
    traffic_light_state TEXT,
    weather_condition TEXT,
    accident_report INTEGER,
    sentiment_score NUMERIC(8, 5),
    ride_sharing_demand INTEGER,
    parking_availability INTEGER,
    emission_levels_g_km NUMERIC(14, 5),
    energy_consumption_l_h NUMERIC(14, 5),
    traffic_condition TEXT
);

